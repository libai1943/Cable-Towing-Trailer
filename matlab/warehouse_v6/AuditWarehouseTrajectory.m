function A=AuditWarehouseTrajectory(R,P)
% Common v6 acceptance: original geometry/replay checks plus every explicit
% grid-state bound and initial-pose clearance. Used identically by all methods.
V=WarehouseValidate(R,P,1);F=WarehouseValidate(R,P,8);cable=WarehouseCableAudit(V.nodes,P);
bounds=max([0,max(abs(R.S))-P.smax,max(abs(R.K))-1/P.radius]);
D=vecnorm(R.X(1:2,:)-R.X(4:5,:));
stateBounds=max([0,.25-min(D),max(D)-P.L,max(abs(R.X([3,6],:)),[],'all')-pi,...
 P.left-min(R.X([1,4],:),[],'all'),max(R.X([1,4],:),[],'all')-P.right,...
 P.ymin-min(R.X([2,5],:),[],'all'),max(R.X([2,5],:),[],'all')-P.ymax]);
[~,iw,is,io]=WarehouseGeometry(P.initial,P);initialClearance=min([iw,is,io]);
A=struct('accepted',V.accepted&&F.accepted&&bounds<1e-7&&stateBounds<1e-7&&initialClearance>=P.clearance-1e-5&&cable.accepted,...
 'stateAccepted',V.accepted,'boundsViolation',bounds,'stateBoundsViolation',stateBounds,'initialClearance',initialClearance,...
 'cost',sum(abs(R.S))+P.regularization*sum(diff(R.K).^2),...
 'travel',sum(abs(R.S)),'cableAccepted',cable.accepted,'cableHits',cable.hits,'cableLengthError',cable.lengthError,...
 'cableSideChanges',cable.sideChanges,'fineStateAccepted',F.accepted,'fineHeadingError',F.headingError,...
 'fineGoalError',F.goalError,'fineNodeDifference',F.maxNodeError,'fineClearance',min([F.wall,F.self,F.obstacle]),...
 'discreteNodeResidual',V.maxNodeError,'modeResidual',V.modeResidual,'coarseClearance',min([V.wall,V.self,V.obstacle]));
end
